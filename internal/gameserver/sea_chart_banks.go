func (b seaChartBank) contains(u, v float64) bool {
	inside := false
	prev := b.pixels[len(b.pixels)-1]
	for _, next := range b.pixels {
		if (prev[1] > v) != (next[1] > v) {
			crossing := prev[0] + (v-prev[1])*(next[0]-prev[0])/(next[1]-prev[1])
			if u < crossing {
				inside = !inside
			}
		}
		prev = next
	}
	return inside
}
